"""Emit the NeoAbs benchmarks page (`docs/benchmarks.md`).

Builds three throwaway MkDocs projects — the same minimal content rendered
with the `neoabs`, `material`, and `readthedocs` themes — then measures the
bytes each site ships (HTML + CSS + JS, raw and gzip) so the docs can publish
a permanent, CI-regenerated page-weight comparison.

Run from the repo root:

    python tools/emit_benchmarks.py

The `mkdocs-material` package must be importable for the `material` column;
when it is missing (or a build fails) the theme shows ``--`` instead of
failing the run, so the tool stays useful on any machine.

Commits generated by the benchmarks workflow are made by a bot, never by this
tool: it only writes `docs/benchmarks.md` and prints what changed.
"""

from __future__ import annotations

import argparse
import gzip
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT_FILE = REPO_ROOT / "docs" / "benchmarks.md"
PROJECT_URL = "https://github.com/rkriad585/mkdocs-neoabs"

# Identical markdown served to every theme so the comparison measures the
# theme's chrome, not the content.
PAGE_SOURCES = {
    "index.md": (
        "# Home\n\n"
        "A paragraph of body text with some **emphasis**, a "
        "[link](https://example.com), and a short list:\n\n"
        "- first item\n"
        "- second item\n"
        "- third item\n"
    ),
    "guide/index.md": (
        "# Guide\n\n"
        "A nested section under a folder so multi-level navigation is exercised.\n"
    ),
    "guide/api.md": (
        "# API\n\n"
        "```python\n"
        "def greet(name: str) -> str:\n"
        "    return f'hello, {name}'\n"
        "```\n\n"
        "> A blockquote showing blockquote styling.\n"
    ),
    "reference/index.md": (
        "# Reference\n\n"
        "## Options\n\n"
        "| Option    | Default     |\n"
        "|-----------|-------------|\n"
        "| `glass`   | `none`      |\n"
        "| `theme`   | `neoabs`    |\n"
    ),
}

# Per-theme mkdocs.yml; only the theme (+ its plugin) differs.
THEME_CONFIGS = {
    "neoabs": "theme:\n  name: neoabs\n",
    "material": "theme:\n  name: material\n",
    "readthedocs": "theme:\n  name: readthedocs\n",
}

# Ordered display order for the table.
THEME_ORDER = ("neoabs", "material", "readthedocs")


def _write_sources(project: Path) -> None:
    for rel, text in PAGE_SOURCES.items():
        path = project / "docs" / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


def _write_config(project: Path, theme: str) -> None:
    theme_block = THEME_CONFIGS[theme]
    plugins = (
        "plugins:\n  - search\n"
        if theme != "neoabs"
        else "plugins:\n  - search\n  - neoabs\n"
    )
    (project / "mkdocs.yml").write_text(
        "site_name: Benchmarks\n"
        + theme_block
        + plugins
        + "markdown_extensions:\n  - tables\n  - admonition\n",
        encoding="utf-8",
    )


def _dir_stats(site: Path) -> dict:
    css = js = other = 0
    files = list(site.rglob("*"))
    for path in files:
        if not path.is_file():
            continue
        size = path.stat().st_size
        if path.suffix == ".css":
            css += size
        elif path.suffix == ".js":
            js += size
        else:
            other += size
    index = (
        (site / "index.html").stat().st_size if (site / "index.html").is_file() else 0
    )
    return {
        "files": len([p for p in files if p.is_file()]),
        "index": index,
        "css": css,
        "js": js,
        "other": other,
    }


def _gzip_bytes(path: Path) -> int:
    if not path.is_file():
        return 0
    return len(gzip.compress(path.read_bytes()))


def _build_theme(theme: str, root: Path) -> dict | None:
    """Build a throwaway project for one theme and report its shipped bytes."""
    project = root / theme
    (project / "docs").mkdir(parents=True, exist_ok=True)
    _write_sources(project)
    _write_config(project, theme)
    site = project / "site"
    proc = subprocess.run(
        [sys.executable, "-m", "mkdocs", "build", "-f", "mkdocs.yml", "-d", "site"],
        cwd=project,
        capture_output=True,
        text=True,
        timeout=300,
        check=False,
    )
    if proc.returncode != 0 or not site.is_dir():
        print(
            f"warning: {theme} build failed:\n{proc.stdout}{proc.stderr}",
            file=sys.stderr,
        )
        return None
    static = _dir_stats(site)
    raw = static["index"] + static["css"] + static["js"] + static["other"]
    wire = sum(_gzip_bytes(p) for p in site.rglob("*") if p.is_file())
    return {"raw": raw, "wire": wire, **static}


def _kb(value: int) -> str:
    return f"{value / 1024:.1f}"


def _table(rows: dict) -> str:
    header = (
        "| Theme | index.html | CSS | JS | Total shipped (raw) | Over the wire (gzip) | Files |\n"
        "|-------|-----------:|----:|----:|-------------------:|---------------------:|------:|\n"
    )
    lines = []
    for theme in THEME_ORDER:
        row = rows.get(theme)
        if row is None or not row.get("ok"):
            lines.append(f"| {theme} | — | — | — | — | — | — |")
            continue
        lines.append(
            f"| {theme} | {_kb(row['index'])} kB | {_kb(row['css'])} kB | "
            f"{_kb(row['js'])} kB | {_kb(row['raw'])} kB | {_kb(row['wire'])} kB | {row['files']} |"
        )
    return header + "\n".join(lines) + "\n"


def _emit(rows: dict, *, mkdocs_version: str, commit: str) -> str:
    date = datetime.now(tz=timezone.utc).date().isoformat()
    lines = [
        "---",
        f"date: {date}",
        "title: Benchmarks",
        "---",
        "",
        "# Benchmarks",
        "",
        f"<!-- generated: do not edit. Run `python tools/emit_benchmarks.py` ({date}). -->",
        "",
        "Page-weight receipts for the themes NeoAbs competes with. The same four",
        "Markdown pages (home, a nested guide with a code block, and a reference",
        "table) are built with `neoabs`, `material`, and `readthedocs`; the table",
        "below is the byte count shipped by each build. **Smaller is faster** —",
        "and this page is regenerated by CI on every push to `main`.",
        "",
        _table(rows),
        f"Measured with MkDocs {mkdocs_version} at commit `{commit}`.",
        "",
        "## Methodology",
        "",
        "- Each project uses the same minimal content and a `search` plugin; only",
        "  the theme differs (`neoabs` additionally registers the `neoabs` plugin,",
        "  the same way a real NeoAbs site does).",
        "- “Total shipped (raw)” sums every file emitted under `site/` (HTML, CSS,",
        "  JS, fonts, and static assets). “Over the wire (gzip)” is the same set",
        "  compressed with gzip to approximate transfer size.",
        "- Themes that cannot be built on a machine (for example `material` when",
        "  `mkdocs-material` is not installed) are shown as “—”; the CI workflow",
        "  installs all three, so the table is always complete upstream.",
        "- No network requests happen during measurement — CDN-only assets are",
        "  counted by what the theme itself ships to the browser.",
        "",
        "## Lighthouse",
        "",
        "Lighthouse runner is enforced in CI, not measured here:",
        f"[`.github/workflows/performance.yml`]({PROJECT_URL}/blob/main/.github/workflows/performance.yml)",
        "asserts a minimum score of **95 in every category** (performance,",
        "accessibility, best-practices, SEO) against the live docs site. A run",
        "that scores below the bar fails the build. Latest runs:",
        f"[Actions → Performance]({PROJECT_URL}/actions/workflows/performance.yml).",
        "",
        "## Regenerating",
        "",
        "```bash",
        "python tools/emit_benchmarks.py",
        "```",
        "",
        "The `Benchmarks` CI workflow runs the same command on every push to",
        "`main` and opens a pull request when the numbers change. To regenerate",
        "manually, add `mkdocs-material` to the environment (`pip install",
        "mkdocs-material`) so the `material` column is populated.",
        "",
    ]
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        default=OUT_FILE,
        type=Path,
        help="output path (default: docs/benchmarks.md)",
    )
    args = parser.parse_args(argv)

    commit = ""
    try:
        proc = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            timeout=30,
            check=False,
        )
        if proc.returncode == 0:
            commit = proc.stdout.strip()
    except (OSError, subprocess.SubprocessError):  # pragma: no cover - no git
        pass

    import mkdocs

    rows = {}
    with tempfile.TemporaryDirectory(prefix="neoabs-bench-") as tmp:
        root = Path(tmp)
        for theme in THEME_ORDER:
            try:
                stats = _build_theme(theme, root)
            except Exception as exc:  # noqa: BLE001 - a broken theme must not kill the page
                print(f"warning: {theme} build raised {exc!r}", file=sys.stderr)
                stats = None
            if stats is None:
                rows[theme] = {"ok": False}
            else:
                rows[theme] = {"ok": True, **stats}

    text = _emit(rows, mkdocs_version=mkdocs.__version__, commit=commit)
    out = args.out.resolve()
    old = out.read_text(encoding="utf-8") if out.is_file() else None
    out.write_text(text, encoding="utf-8")
    changed = "unchanged" if text == old else "changed"
    print(
        f"wrote {out.relative_to(REPO_ROOT)} ({changed}, {len(text.splitlines())} lines)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
